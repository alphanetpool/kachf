const normalizeArabic = (text: string) =>
  text
    .trim()
    .replace(/[\u064B-\u065F\u0670]/g, "")
    .replace(/[أإآ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي");

const getReductionSteps = (sum: number) => {
  const steps: number[] = [sum];
  let current = sum;
  while (current > 9) {
    current = current
      .toString()
      .split("")
      .reduce((acc, digit) => acc + Number(digit), 0);
    steps.push(current);
  }
  return steps;
};

const getNameBreakdown = (name: string, source: "person" | "mother") => {
  const normalized = normalizeArabic(name);
  const letters: LetterBreakdown[] = normalized
    .split("")
    .filter((char) => ABJAD_VALUES[char])
    .map((char) => ({
      letter: char,
      value: ABJAD_VALUES[char],
      source,
    }));
  const sum = letters.reduce((acc, item) => acc + item.value, 0);
  return { normalized, letters, sum };
};

const formatReduction = (step: number) => step.toString().split("").join(" + ");

